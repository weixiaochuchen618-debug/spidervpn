# 用 .NET（不是本项目的 Rust 代码）生成一条 RS256 邀请 JWT，作为**外部实现**向量。
#
# 为什么需要它：`verify_rs256` 如果只被我自己的签名器验过，那就是「我的理解 vs 我的实现」。
# 这里的签名走 `RSA.SignData(Pkcs1, SHA256)`，与 jose-jwt 的 RS256 是同一套原语。
#
# 用法：powershell -ExecutionPolicy Bypass -File tools\Gen-PairingJwt.ps1
# 产物：tests\fixtures\pairing\dotnet-jwt-1.json

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Security

function ConvertTo-Base64Url([byte[]]$Bytes) {
    [Convert]::ToBase64String($Bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

$rsa = [System.Security.Cryptography.RSA]::Create(2048)
try {
    $private = $rsa.ExportParameters($true)
    $public = $rsa.ExportParameters($false)
    $jwk = [ordered]@{
        kty = 'RSA'
        n   = (ConvertTo-Base64Url $public.Modulus)
        e   = (ConvertTo-Base64Url $public.Exponent)
    }

    # 时间固定：向量必须是可重复的，不能随生成时刻变化。
    $payload = [ordered]@{
        SchemaVersion             = 1
        Kind                      = 'TradeChannel.PairInvite'
        InviteId                  = '9f1c2a44-0b7d-4c1e-9a2b-3c4d5e6f7a8b'
        RemoteOwnerId             = 'owner-1'
        NodeId                    = 'node-1'
        ServerPublicKey           = 'server-public-key'
        ManagementSigningPublicKey = $jwk
        PublicEndpoint            = '203.0.113.10:18443'
        IssuedAtUtc               = '2027-01-01T00:00:00Z'
        ExpiresAtUtc              = '2027-06-01T00:00:00Z'
        Capabilities              = @()
        ServerBinding             = [ordered]@{
            RemoteOwnerId   = 'owner-1'
            NodeId          = 'node-1'
            ServerPublicKey = 'server-public-key'
        }
        DeviceName                = '管理电脑'
    }

    $headerJson = '{"alg":"RS256","typ":"JWT"}'
    $payloadJson = $payload | ConvertTo-Json -Depth 8 -Compress
    $headerB64 = ConvertTo-Base64Url ([Text.Encoding]::UTF8.GetBytes($headerJson))
    $payloadB64 = ConvertTo-Base64Url ([Text.Encoding]::UTF8.GetBytes($payloadJson))
    $signingInput = "$headerB64.$payloadB64"
    $signature = $rsa.SignData(
        [Text.Encoding]::ASCII.GetBytes($signingInput),
        [System.Security.Cryptography.HashAlgorithmName]::SHA256,
        [System.Security.Cryptography.RSASignaturePadding]::Pkcs1)
    $compact = "$signingInput." + (ConvertTo-Base64Url $signature)

    $fixture = [ordered]@{
        note      = 'test fixture, never use for real pairing; generated by tools/Gen-PairingJwt.ps1 (.NET, not this repo''s Rust code)'
        publicJwk = $jwk
        compact   = $compact
        payload   = $payload
    }
    $path = Join-Path $PSScriptRoot '..\tests\fixtures\pairing\dotnet-jwt-1.json'
    # 数据文件不能带 BOM：serde_json 会把 BOM 当非法字符（"expected value at line 1 column 1"）。
    $json = $fixture | ConvertTo-Json -Depth 10
    [IO.File]::WriteAllText($path, $json, (New-Object Text.UTF8Encoding($false)))
    Write-Output "written: $path"
}
finally {
    $rsa.Dispose()
}
